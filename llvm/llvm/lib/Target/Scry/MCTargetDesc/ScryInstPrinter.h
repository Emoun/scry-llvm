#ifndef LLVM_LIB_TARGET_SCRY_MCTARGETDESC_SCRYINSTPRINTER_H
#define LLVM_LIB_TARGET_SCRY_MCTARGETDESC_SCRYINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class ScryInstPrinter : public MCInstPrinter {
public:
  ScryInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Automatically generated by TableGen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printRef(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printIdx(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printType(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printSizeType(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPow2(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm8(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_SCRY_MCTARGETDESC_SCRYINSTPRINTER_H
