#ifndef LLVM_LIB_TARGET_SCRY_SCRYSUBTARGET_H
#define LLVM_LIB_TARGET_SCRY_SCRYSUBTARGET_H

#include "ScryFrameLowering.h"
#include "ScryISelLowering.h"
#include "ScryInstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "ScryGenSubtargetInfo.inc"

namespace llvm {

class ScrySubtarget : public ScryGenSubtargetInfo {
  ScryInstrInfo InstrInfo;
  ScryFrameLowering FrameLowering;
  ScryTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;

public:
  ScrySubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const TargetMachine &TM);

  // Auto-generated by TableGen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const ScryInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const ScryRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const ScryTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_SCRY_SCRYSUBTARGET_H
